/**
 * Clean & normalize string
 */
function cleanKey(str) {
  if (!str) return '';
  return str
    .toLowerCase()
    .trim()
    .normalize('NFD')
    .replace(/[\u0300-\u036f]/g, '')
    .replace(/ß/g, 'ss')
    .replace(/\s+/g, ' ');
}

/**
 * Finds French translation for any German word or answer
 */
export function getFrenchTranslationForGerman(germanWord, additionalLists = []) {
  if (!germanWord) return '';
  const cleaned = cleanKey(germanWord);

  // 1. Direct dictionary match
  if (defaultDictionary[cleaned]) {
    return defaultDictionary[cleaned];
  }

  // 2. Also check direct match with umlauts intact
  const rawKey = germanWord.toLowerCase().trim();
  if (defaultDictionary[rawKey]) {
    return defaultDictionary[rawKey];
  }

  // 3. Search in additional lists / exampleLists
  if (Array.isArray(additionalLists)) {
    for (const list of additionalLists) {
      if (Array.isArray(list?.words)) {
        for (const item of list.words) {
          if (cleanKey(item.answer) === cleaned) {
            return item.question || item.french || item.english || '';
          }
        }
      }
    }
  }

  // 4. Try matching without German articles (der/die/das/ein/eine)
  const articles = ['der', 'die', 'das', 'den', 'dem', 'des', 'ein', 'eine', 'einen'];
  const parts = cleaned.split(' ');
  if (parts.length > 1 && articles.includes(parts[0])) {
    const nounOnly = parts.slice(1).join(' ');
    // Search dictionary keys ending with nounOnly
    for (const [key, val] of Object.entries(defaultDictionary)) {
      const keyParts = cleanKey(key).split(' ');
      if (keyParts.slice(1).join(' ') === nounOnly || cleanKey(key) === nounOnly) {
        return val;
      }
    }
  }

  return '';
}

/**
 * Helper to ensure a failed word has a distinct French prompt and German expected answer
 */
export function resolveWordPair(item, additionalLists = []) {
  let germanWord = '';
  let frenchPrompt = '';
  let count = 1;

  if (typeof item === 'string') {
    germanWord = item;
  } else if (typeof item === 'object' && item !== null) {
    count = item.count || 1;
    germanWord = item.word || item.answer || '';
    frenchPrompt = item.question || item.french || item.fr || item.translation || item.english || '';
  }

  // If frenchPrompt is identical to germanWord, or contains generic instructions, or is empty:
  const isGeneric = !frenchPrompt || 
                    frenchPrompt.toLowerCase().includes('traduire') || 
                    cleanKey(frenchPrompt) === cleanKey(germanWord);

  if (isGeneric && germanWord) {
    const foundFrench = getFrenchTranslationForGerman(germanWord, additionalLists);
    if (foundFrench) {
      frenchPrompt = foundFrench;
    } else {
      // If no translation exists, clean up and clarify
      frenchPrompt = germanWord;
    }
  }

  return {
    germanWord,
    frenchPrompt,
    count
  };
}
